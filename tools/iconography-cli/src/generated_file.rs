use cloud_terrastodon_app::CancellationScope;
use eyre::Result;
use eyre::WrapErr;
use eyre::ensure;
use std::collections::BTreeSet;
use std::fs;
use std::io::Write;
use std::path::Path;
use std::path::PathBuf;
use tempfile::NamedTempFile;

/// A rendered repository artifact ready for comparison or persistence.
#[derive(Debug)]
pub struct GeneratedFile {
    pub path: PathBuf,
    pub contents: Vec<u8>,
}

/// Stage changed artifacts before protecting their final replacement from cancellation.
///
/// Individual replacements are atomic. A filesystem error may interrupt the batch;
/// running `generate` again repairs generated-file drift after the error is resolved.
pub fn write_files(
    files: Vec<GeneratedFile>,
    obsolete: Vec<PathBuf>,
    scope: &CancellationScope,
) -> Result<Vec<PathBuf>> {
    let mut paths = BTreeSet::new();
    let mut staged = Vec::new();
    for file in files {
        scope.bail_if_cancelled()?;
        ensure!(
            paths.insert(file.path.clone()),
            "duplicate output path {}",
            file.path.display()
        );
        match fs::read(&file.path) {
            Ok(existing) if existing == file.contents => continue,
            Ok(existing) => {
                // `planned_files` validates the narrow initial lib.rs migration
                // and preserves its test modules before proposing this output.
                ensure!(
                    !is_generated_source(&file.contents)
                        || is_generated_source(&existing)
                        || file.path.file_name().is_some_and(|name| name == "lib.rs"),
                    "generated output would overwrite an unmarked source file; preserving {}",
                    file.path.display()
                );
            }
            Err(error) if error.kind() == std::io::ErrorKind::NotFound => {}
            Err(error) => {
                return Err(error).wrap_err_with(|| format!("reading {}", file.path.display()));
            }
        }
        let parent = file
            .path
            .parent()
            .ok_or_else(|| eyre::eyre!("output has no parent: {}", file.path.display()))?;
        fs::create_dir_all(parent).wrap_err_with(|| format!("creating {}", parent.display()))?;
        let mut temporary = NamedTempFile::new_in(parent)
            .wrap_err_with(|| format!("staging {}", file.path.display()))?;
        temporary
            .write_all(&file.contents)
            .wrap_err_with(|| format!("writing staged {}", file.path.display()))?;
        temporary
            .as_file()
            .sync_all()
            .wrap_err_with(|| format!("syncing staged {}", file.path.display()))?;
        staged.push((file.path, temporary));
    }
    for path in &obsolete {
        scope.bail_if_cancelled()?;
        ensure!(
            paths.insert(path.clone()),
            "obsolete source conflicts with another output: {}",
            path.display()
        );
        validate_obsolete_source(path)?;
    }
    scope.with_deferral(
        "finish replacing staged iconography artifacts",
        |protected| {
            let mut changed = Vec::new();
            for (path, temporary) in staged {
                protected.bail_if_cancelled()?;
                temporary
                    .persist(&path)
                    .wrap_err_with(|| format!("replacing {}", path.display()))?;
                changed.push(path);
            }
            for path in obsolete {
                protected.bail_if_cancelled()?;
                validate_obsolete_source(&path)?;
                fs::remove_file(&path).wrap_err_with(|| {
                    format!("removing obsolete generated source {}", path.display())
                })?;
                changed.push(path);
            }
            Ok(changed)
        },
    )
}

/// Recognize only the exact first-line marker emitted by this generator.
pub fn is_generated_source(contents: &[u8]) -> bool {
    let line = contents
        .split(|byte| *byte == b'\n')
        .next()
        .unwrap_or_default();
    line.strip_suffix(b"\r").unwrap_or(line)
        == b"// @generated by iconography-cli generate; do not edit."
}

fn validate_obsolete_source(path: &Path) -> Result<()> {
    let parent = path
        .parent()
        .ok_or_else(|| eyre::eyre!("obsolete source has no parent: {}", path.display()))?;
    let parent_metadata = fs::symlink_metadata(parent)
        .wrap_err_with(|| format!("rechecking obsolete source directory {}", parent.display()))?;
    ensure!(
        parent_metadata.is_dir() && !parent_metadata.file_type().is_symlink(),
        "obsolete source directory must remain a regular directory: {}",
        parent.display()
    );
    let metadata = fs::symlink_metadata(path)
        .wrap_err_with(|| format!("examining obsolete source {}", path.display()))?;
    ensure!(
        metadata.is_file() && !metadata.file_type().is_symlink(),
        "obsolete generated source must remain a regular file: {}",
        path.display()
    );
    ensure!(
        path.extension().is_some_and(|extension| extension == "rs")
            && path
                .parent()
                .and_then(Path::file_name)
                .is_some_and(|name| name == "src"),
        "obsolete generated source must be directly inside its src directory: {}",
        path.display()
    );
    let contents = fs::read(path)
        .wrap_err_with(|| format!("rechecking obsolete source {}", path.display()))?;
    ensure!(
        is_generated_source(&contents),
        "obsolete source lost its generated marker; preserving {}",
        path.display()
    );
    Ok(())
}
